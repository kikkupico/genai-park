#!/usr/bin/env python3
"""Copy the formula glossary (GLOSS) out of the archived site's park.js into gloss.js.
Run from the repo root after changing the glossary in archive/park/park.js:  python3 tools/build-gloss.py"""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
src = (root / 'archive' / 'park' / 'park.js').read_text()
i = src.index('const GLOSS=') + len('const GLOSS=')
j = src.index('function glossOf')
blk = src[i:j].strip().rstrip(';')
out = root / 'gloss.js'
out.write_text('/* Generated by tools/build-gloss.py from archive/park/park.js. Do not edit by hand. */\nwindow.GLOSS=' + blk + ';\n')
print('wrote', out.relative_to(root), len(blk), 'chars')
